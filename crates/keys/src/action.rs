use serde::{Deserialize, Serialize};

/// 键盘（以及鼠标翻译过来）能触发的全部动作。同一个动作在不同上下文里由 model 解释，
/// 例如 `Open` 在会话列表里是"打开会话"，在实例选择里是"接入"。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum Action {
    // 全局
    Help,
    TabSessions,
    TabFlows,
    TabJobs,
    FocusToggle,
    PaneToggle,
    NextAttention,
    MouseToggle,
    Interrupt,
    Detach,
    Redraw,
    Back,
    EventLog,
    ToggleDetail,
    TogglePanel,
    LineUp,
    LineDown,
    FocusPanel,
    CycleMode,
    Exit,

    // 输入框
    Submit,
    Newline,
    Complete,
    CursorLeft,
    CursorRight,
    WordLeft,
    WordRight,
    LineStart,
    LineEnd,
    ClearInput,
    DeleteWord,
    KillToEnd,
    Backspace,
    DeleteForward,
    FocusTranscript,

    // 滚动与列表
    Up,
    Down,
    PageUp,
    PageDown,
    Top,
    Bottom,
    Collapse,
    Expand,
    Open,
    SwitchSection,
    Filter,
    RatioDec,
    RatioInc,
    BlockPrev,
    BlockNext,

    // 列表项上的操作
    New,
    Rename,
    Close,
    Edit,
    PauseResume,
    Message,
    Stop,
    View,
    Confirm,
    Release,
    Force,
    Rework,
    Retry,
    ToggleEnabled,
    RunNow,
    Delete,
    Quit,

    // 对话框
    Yes,
    No,
    NextPrompt,
    PrevPrompt,
    Choose1,
    Choose2,
    Choose3,
    Choose4,
    Choose5,
    Choose6,
    Choose7,
    Choose8,
    Choose9,
}

